// Manual verification script (Toolkit productization pass, P0-6, PDF
// Search) - NOT part of the regular regression suite. Drives
// ViewPdfController against a real, visually-labeled 4-page PDF containing
// "Azure Kubernetes Service" / "Kubernetes" / "Terraform" / "GitHub
// Actions" on different pages (the P0-6 spec's own exact example terms),
// verifies match count/page/navigation, writes the visual PDF for
// inspection, and separately verifies a scanned/image-only PDF is honestly
// reported as having no searchable text (never falsely claimed
// searchable) - `read_pdf_text` itself is a real native plugin with no
// implementation under `flutter test` (the same standing limitation as
// `Printing.raster`, R-32), so its extraction output is faked here with
// text that matches what a real born-digital PDF built from this exact
// visual content would extract, while the PDF itself (for visual
// inspection) is 100% really generated by `PdfPageComposerService`.
//
// Run with: flutter test test/manual/generate_pdf_search_demo_test.dart
