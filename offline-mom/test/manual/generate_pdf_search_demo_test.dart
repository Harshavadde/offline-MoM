class _FakePathProviderPlatform extends PathProviderPlatform {
  _FakePathProviderPlatform(this._path);
  final String _path;
  @override
  Future<String?> getApplicationDocumentsPath() async => _path;
}

const _pageTexts = [
  'Azure Kubernetes Service (AKS) is a managed Kubernetes offering.',
  'Terraform lets you define infrastructure as code declaratively.',
  'This deployment uses Kubernetes namespaces for isolation between teams.',
  'GitHub Actions automates the build and deploy pipeline end to end.',
];

class _LabeledTextPdfPageRenderingService implements PdfPageRenderingService {
  _LabeledTextPdfPageRenderingService(this.pageTexts);
  final List<String> pageTexts;

  @override
  Stream<RasterizedPdfPage> rasterizePages(
    Uint8List pdfBytes, {
    List<int>? pageIndices,
    double dpi = kPdfOutputDpi,
    int jpegQuality = 90,
    bool cropToContent = false,
  }) async* {
    const width = 600, height = 500;
    final indices = pageIndices ?? List.generate(pageTexts.length, (i) => i);
    for (final index in indices) {
      final image = img.Image(width: width, height: height);
      img.fill(image, color: img.ColorRgb8(255, 255, 255));
      img.drawString(image, 'Page ${index + 1}', font: img.arial24, x: 30, y: 30, color: img.ColorRgb8(20, 20, 20));
      img.drawString(image, pageTexts[index], font: img.arial14, x: 30, y: 90, color: img.ColorRgb8(40, 40, 40), wrap: true);
      final jpegBytes = img.encodeJpg(image, quality: jpegQuality);
      final tempPath = await newToolkitTempFilePath('jpg');
      await File(tempPath).writeAsBytes(jpegBytes);
      yield RasterizedPdfPage(tempFilePath: tempPath, width: width, height: height, pageIndex: index);
    }
  }
}

/// Stands in for `read_pdf_text`'s real native extraction - returns text
/// matching exactly what the visual content above says, since the real
/// plugin can't run under `flutter test`.
class _FixedPdfTextSearchService implements PdfTextSearchService {
  _FixedPdfTextSearchService(this.pagesText);
  final List<String> pagesText;
  @override
  Future<List<String>> extractPagesText(String pdfFilePath) async => pagesText;
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('searches a real 4-page PDF for each of the spec\'s own example terms and verifies correct '
      'match count/page/navigation; writes the visual PDF for inspection', () async {
    final docsDir = await Directory.systemTemp.createTemp('pdf_search_demo_test_');
    PathProviderPlatform.instance = _FakePathProviderPlatform(docsDir.path);
    addTearDown(() async {
      if (await docsDir.exists()) await docsDir.delete(recursive: true);
    });

    final pickerService = FakeToolkitFilePickerService()
      ..pdfResult = PickedToolkitFile(fileName: 'demo-search.pdf', bytes: Uint8List.fromList([1, 2, 3]));
    final container = ProviderContainer(
      overrides: [
        toolkitFilePickerServiceProvider.overrideWithValue(pickerService),
        pdfPageRenderingServiceProvider.overrideWithValue(_LabeledTextPdfPageRenderingService(_pageTexts)),
        pdfTextSearchServiceProvider.overrideWithValue(_FixedPdfTextSearchService(_pageTexts)),
      ],
    );
    addTearDown(container.dispose);

    final controller = container.read(viewPdfControllerProvider.notifier);
    await controller.pickPdf();
    expect(container.read(viewPdfControllerProvider).pages, hasLength(4));

    // Write the real visual PDF for inspection - build it the same way the
    // screen would show it, one page at a time, by composing the already-
    // rasterized page images back into a real PDF via the shared composer.
    // (ViewPdfController itself never writes a PDF - it's a read-only
    // viewer - so this uses the pages it already rasterized directly.)
    await controller.ensureTextExtracted();

    // "Azure Kubernetes Service" - appears once, on page 1.
    controller.setSearchQuery('Azure Kubernetes Service');
    var state = container.read(viewPdfControllerProvider);
    expect(state.matches.map((m) => m.pageIndex), [0]);
    expect(state.currentPage, 0);
    // ignore: avoid_print
    print('OK   "Azure Kubernetes Service" -> ${state.totalOccurrences} match on page(s) '
        '${state.matches.map((m) => m.pageIndex + 1).toList()}');

    // "Kubernetes" - appears on page 1 (within "Azure Kubernetes Service")
    // and page 3.
    controller.setSearchQuery('Kubernetes');
    state = container.read(viewPdfControllerProvider);
    expect(state.matches.map((m) => m.pageIndex), [0, 2]);
    // ignore: avoid_print
    print('OK   "Kubernetes" -> ${state.totalOccurrences} matches on page(s) '
        '${state.matches.map((m) => m.pageIndex + 1).toList()}');

    // "Terraform" - page 2 only.
    controller.setSearchQuery('Terraform');
    state = container.read(viewPdfControllerProvider);
    expect(state.matches.map((m) => m.pageIndex), [1]);
    expect(state.currentPage, 1);
    // ignore: avoid_print
    print('OK   "Terraform" -> ${state.totalOccurrences} match on page(s) ${state.matches.map((m) => m.pageIndex + 1).toList()}');

    // "GitHub Actions" - page 4 only.
    controller.setSearchQuery('GitHub Actions');
    state = container.read(viewPdfControllerProvider);
    expect(state.matches.map((m) => m.pageIndex), [3]);
    expect(state.currentPage, 3);
    // ignore: avoid_print
    print('OK   "GitHub Actions" -> ${state.totalOccurrences} match on page(s) ${state.matches.map((m) => m.pageIndex + 1).toList()}');

    // Next/previous navigation across the "Kubernetes" result set.
    controller.setSearchQuery('Kubernetes');
    controller.nextMatch();
    expect(container.read(viewPdfControllerProvider).currentPage, 2); // second match, page 3
    controller.previousMatch();
    expect(container.read(viewPdfControllerProvider).currentPage, 0); // back to first match, page 1
    // ignore: avoid_print
    print('OK   next/previous navigation moved correctly between pages 1 and 3');

    final outDir = Directory(_outputDir)..createSync(recursive: true);
    final pagesInputs = [
      for (final page in container.read(viewPdfControllerProvider).pages)
        PdfPageInput(jpegBytes: page.jpegBytes, width: page.width, height: page.height),
    ];
    final composed = await PdfPageComposerService().compose(pagesInputs);
    final file = File('${outDir.path}/pdf_search_demo.pdf');
    await file.writeAsBytes(composed);
    // ignore: avoid_print
    print('OK   wrote ${file.path} (${composed.length} bytes) - open and search for the terms above');
  });

  test('a scanned/image-only PDF (no extractable text) is never falsely reported as searchable', () async {
    final docsDir = await Directory.systemTemp.createTemp('pdf_search_scanned_demo_test_');
    PathProviderPlatform.instance = _FakePathProviderPlatform(docsDir.path);
    addTearDown(() async {
      if (await docsDir.exists()) await docsDir.delete(recursive: true);
    });

    final pickerService = FakeToolkitFilePickerService()
      ..pdfResult = PickedToolkitFile(fileName: 'scanned.pdf', bytes: Uint8List.fromList([1]));
    final container = ProviderContainer(
      overrides: [
        toolkitFilePickerServiceProvider.overrideWithValue(pickerService),
        pdfPageRenderingServiceProvider.overrideWithValue(_LabeledTextPdfPageRenderingService(['', '', ''])),
        pdfTextSearchServiceProvider.overrideWithValue(_FixedPdfTextSearchService(const ['', '', ''])),
      ],
    );
    addTearDown(container.dispose);

    final controller = container.read(viewPdfControllerProvider.notifier);
    await controller.pickPdf();
    await controller.ensureTextExtracted();

    final state = container.read(viewPdfControllerProvider);
    expect(state.hasExtractedText, isTrue);
    expect(state.isSearchable, isFalse);
    // ignore: avoid_print
    print('OK   scanned/image-only PDF correctly reports isSearchable=false (no false positive)');
  });
}
